const { _electron: electron, expect } = require('@playwright/test')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const assert = require('node:assert/strict')
const iconv = require('iconv-lite')

async function main() {
  const root = path.resolve(__dirname, '..')
  const fixtures = await fs.mkdtemp(path.join(os.tmpdir(), 'zhimo-smoke-'))
  const a = path.join(fixtures, '01-写作.md')
  const b = path.join(fixtures, '02-阅读.md')
  const original = '# 写作的节奏\n\n让想法有一个呼吸的位置。\n\n## 待办\n\n- [x] 已完成\n- [ ] 继续写作\n\n```javascript\nconst paper = true\n```\n\n| 项目 | 状态 |\n| --- | --- |\n| 编辑 | 完成 |\n\n$$\nE=mc^2\n$$\n'
  const imageName = '纸页100%20.png'
  await fs.copyFile(path.join(root, 'assets/app-icon.png'), path.join(fixtures, imageName))
  await fs.writeFile(a, original + `\n![本地图](${encodeURIComponent(imageName)})\n`)
  await fs.writeFile(b, '# 阅读\n\n另一份文稿，不应被撤销覆盖。\n')
  const nav = path.join(fixtures, '03-大纲.md')
  await fs.writeFile(nav, '# Topic\n\n# Topic\n\n# Topic-1\n\n[跳转到文稿](02-阅读.md#外部新内容)\n')
  const env = { ...process.env, ZHIMO_USER_DATA_DIR: path.join(fixtures, 'profile') }
  await fs.mkdir(env.ZHIMO_USER_DATA_DIR, { recursive: true })
  delete env.ELECTRON_RUN_AS_NODE
  delete env.ELECTRON_RENDERER_URL
  let app
  const errors = []
  const passed = []
  const ok = label => { passed.push(label); console.log('PASS', label) }
  try {
    app = await electron.launch({ args: ['.', a], cwd: root, env, timeout: 30000 })
    const page = await app.firstWindow()
    page.setDefaultTimeout(10000)
    await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.restore(); w.show(); w.focus() })
    page.on('pageerror', error => errors.push(error.message))
    await expect(page.locator('.cm-content')).toContainText('写作的节奏', { timeout: 30000 })
    await expect(page.locator('.md h1')).toContainText('写作的节奏')
    await expect(page.locator('.md table')).toBeVisible()
    await expect(page.locator('.md .katex')).toHaveCount(1)
    ok('real Electron starts; editor, table and math render')
    const localImage = page.getByRole('img', { name: '本地图' })
    await localImage.scrollIntoViewIfNeeded()
    await expect.poll(() => localImage.evaluate(img => img.naturalWidth)).toBe(512)
    ok('local image with Chinese and literal percent characters renders')
    const input = page.locator('.cm-content')
    await input.click()
    await page.keyboard.press('Control+End')
    await page.keyboard.insertText('\n自动保存验证')
    console.log('EDIT STATE', await page.evaluate(() => ({ editor: document.querySelector('.cm-content')?.textContent, status: document.querySelector('.saved')?.textContent, banners: [...document.querySelectorAll('.banner')].map(e=>e.textContent), active: document.activeElement?.className })))
    await page.waitForTimeout(1400)
    console.log('SAVE STATE', await page.evaluate(() => ({ status: document.querySelector('.saved')?.textContent, banners: [...document.querySelectorAll('.banner')].map(e=>e.textContent) })))
    await expect.poll(() => fs.readFile(a, 'utf8')).toContain('自动保存验证')
    ok('typing auto-saves to the actual file')
    await page.getByRole('button', { name: /02-阅读.md/ }).click()
    await expect(input).toContainText('另一份文稿')
    await input.click()
    await page.keyboard.press('Control+z')
    await expect(input).toContainText('另一份文稿')
    await expect(input).not.toContainText('写作的节奏')
    ok('switching documents resets undo history')
    await page.getByRole('button', { name: /01-写作.md/ }).click()
    await expect(input).toContainText('自动保存验证')
    await fs.writeFile(a, '# 外部改动\n\n外部版本\n')
    await expect(page.getByText('文件在外部被修改过。')).toBeVisible({ timeout: 10000 })
    await input.click()
    await page.keyboard.press('Control+End')
    await page.keyboard.insertText('\n保留本地改动')
    await page.waitForTimeout(1200)
    assert.equal(await fs.readFile(a, 'utf8'), '# 外部改动\n\n外部版本\n')
    ok('external edits pause autosave and preserve disk contents')
    await page.getByRole('button', { name: '保留我的版本' }).click()
    await expect.poll(() => fs.readFile(a, 'utf8')).toContain('保留本地改动')
    ok('explicit conflict overwrite saves the chosen version')
    // A malformed local document must not execute embedded JavaScript.
    await input.click()
    await page.keyboard.press('Control+End')
    await page.keyboard.insertText('\n<img src=x onerror="window.__injected=1"><script>window.__injected=2</script>\n')
    await page.waitForTimeout(300)
    assert.equal(await page.evaluate(() => window.__injected), undefined)
    assert.equal(await page.locator('.md script, .md [onerror]').count(), 0)
    ok('preview sanitizes untrusted HTML before insertion')
    await page.getByRole('button', { name: '阅读', exact: true }).click()
    await expect(page.locator('.pane-editor')).toBeHidden()
    await page.getByRole('button', { name: '写作', exact: true }).click()
    await expect(page.locator('.pane-preview')).toBeHidden()
    await page.getByRole('button', { name: '对照', exact: true }).click()
    await page.getByTitle('切到夜墨 (Ctrl+\\)').click()
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'ink')
    await page.getByTitle('切到宣纸 (Ctrl+\\)').click()
    await page.getByTitle(/关闭界面音效/).click()
    await page.getByTitle(/开启界面音效/).click()
    ok('view, theme and sound controls work without runtime errors')
    const win = await app.browserWindow(page)
    await win.evaluate(w => w.setSize(720, 640))
    await page.waitForTimeout(150)
    const layout = await page.evaluate(() => ({
      w: innerWidth, overflow: document.documentElement.scrollWidth > innerWidth,
      editor: document.querySelector('.pane-editor').getBoundingClientRect().width,
      preview: document.querySelector('.pane-preview').getBoundingClientRect().width
    }))
    assert.equal(layout.overflow, false, JSON.stringify(layout))
    assert.ok(layout.editor > 600 && layout.preview > 600, JSON.stringify(layout))
    await fs.mkdir(path.join(root, 'artifacts'), { recursive: true })
    await page.screenshot({ path: path.join(root, 'artifacts/zhimo-narrow.png') })
    ok('720px window keeps both panes readable with no horizontal overflow')
    // Encoding and BOM preservation through the public host boundary.
    for (const [name, encoding, bom, text] of [
      ['utf8-bom.md', 'utf-8', true, '# 中文\r\n内容\r\n'],
      ['utf16.md', 'utf16-le', true, '# 中文\r\n内容\r\n'],
      ['gb18030.md', 'gb18030', false, '# 中文测试\r\n这是需要保留的内容。\r\n'],
      ['big5.md', 'big5', false, '繁體中文測試：閱讀紙墨編輯器，保留原來的標點以及字體。'.repeat(8) + '\r\n']
    ]) {
      const p = path.join(fixtures, name)
      let bytes = iconv.encode(text, encoding)
      if (bom) bytes = Buffer.concat([encoding === 'utf-8' ? Buffer.from([239,187,191]) : Buffer.from([255,254]), bytes])
      await fs.writeFile(p, bytes)
      const doc = await page.evaluate(p => window.host.read(p), p)
      assert.ok(!doc.error, JSON.stringify(doc))
      assert.equal(doc.content, text.replace(/\r\n/g, '\n'), name)
      const saved = await page.evaluate(({p,doc}) => window.host.write(p, { content: doc.content, encoding: doc.encoding, eol: doc.eol, bom: doc.bom, expected: doc.version }), { p, doc })
      assert.ok(!saved.error, JSON.stringify(saved))
      assert.deepEqual(await fs.readFile(p), bytes, name)
    }
    ok('UTF8 BOM, UTF16 and GB18030 retain exact bytes on round trip')
    const stale = await page.evaluate(p => window.host.read(p), b)
    await fs.writeFile(b, '# 外部新内容\n')
    const conflict = await page.evaluate(({p,d}) => window.host.write(p, { ...d, content: 'should not overwrite', expected: d.version }), {p:b,d:stale})
    assert.equal(conflict.conflict, true)
    assert.equal(await fs.readFile(b, 'utf8'), '# 外部新内容\n')
    ok('native write rejects a stale disk version')
    await page.keyboard.press('Control+s')
    await expect(page.locator('.saved')).toContainText('已保存')
    await win.evaluate(w => w.setSize(1280, 860))
    await page.getByRole('button', { name: /03-大纲.md/ }).click()
    await expect(page.locator('.md h1')).toHaveCount(3)
    const ids = await page.locator('.md h1').evaluateAll(items => items.map(item => item.id))
    assert.equal(new Set(ids).size, 3)
    await page.getByRole('button', { name: '写作', exact: true }).click()
    await page.locator(`aside a[href="#${ids[2]}"]`).click()
    await expect(page.locator('.cm-activeLine')).toContainText('Topic-1')
    await page.getByRole('button', { name: '对照', exact: true }).click()
    await page.getByRole('link', { name: '跳转到文稿' }).click()
    await expect(input).toContainText('外部新内容')
    await page.getByRole('button', { name: /01-写作.md/ }).click()
    await expect(input).toContainText('保留本地改动')
    ok('unique outline IDs, write-mode outline and cross-document link')
    // Return to a clean visual specimen for the large-window screenshot.
    await fs.writeFile(a, original)
    await expect(page.getByText('文件在外部被修改过。')).toBeVisible({ timeout: 10000 })
    await page.getByRole('button', { name: '重新载入' }).click()
    await win.evaluate(w => w.setSize(1280, 860))
    await page.waitForTimeout(200)
    await page.screenshot({ path: path.join(root, 'artifacts/zhimo-paper.png') })
    // Dirty close must offer explicit choices instead of silently saving.
    await input.click()
    await page.keyboard.press('Control+End')
    await page.keyboard.insertText('\n关闭前的最后一句')
    await page.evaluate(() => { void window.host.requestClose() })
    const closeDialog = page.getByRole('alertdialog')
    await expect(closeDialog).toBeVisible()
    await expect(closeDialog).toContainText('要保存这次修改吗？')
    await closeDialog.getByRole('button', { name: '继续编辑' }).click()
    await expect(closeDialog).toBeHidden()
    await expect(page.locator('.saved')).toContainText('有改动')
    await page.evaluate(() => { void window.host.requestClose() })
    await expect(closeDialog).toBeVisible()
    const closed = page.waitForEvent('close')
    await closeDialog.getByRole('button', { name: '保存并退出' }).click()
    await closed
    assert.ok((await fs.readFile(a, 'utf8')).includes('关闭前的最后一句'))
    ok('dirty close asks first; cancel keeps editing and save choice flushes')
    assert.deepEqual(errors, [], 'renderer errors')

    // Reopen a separate profile to confirm the discard path leaves disk untouched.
    const beforeDiscard = await fs.readFile(a, 'utf8')
    const discardEnv = { ...env, ZHIMO_USER_DATA_DIR: path.join(fixtures, 'discard-profile') }
    await fs.mkdir(discardEnv.ZHIMO_USER_DATA_DIR, { recursive: true })
    app = await electron.launch({ args: ['.', a], cwd: root, env: discardEnv, timeout: 30000 })
    const discardPage = await app.firstWindow()
    discardPage.setDefaultTimeout(10000)
    await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.restore(); w.show(); w.focus() })
    const discardInput = discardPage.locator('.cm-content')
    await expect(discardInput).toContainText('关闭前的最后一句')
    await discardInput.click()
    await discardPage.keyboard.press('Control+End')
    await discardPage.keyboard.insertText('\n这段内容应该被放弃')
    await discardPage.evaluate(() => { void window.host.requestClose() })
    const discardDialog = discardPage.getByRole('alertdialog')
    await expect(discardDialog).toBeVisible()
    const discardClosed = discardPage.waitForEvent('close')
    await discardDialog.getByRole('button', { name: '不保存，退出' }).click()
    await discardClosed
    assert.equal(await fs.readFile(a, 'utf8'), beforeDiscard)
    ok('discard choice closes without persisting pending changes')
    assert.deepEqual(errors, [], 'renderer errors')
    console.log(JSON.stringify({ passed: passed.length, errors, fixtureDirectory: fixtures }, null, 2))
  } finally {
    if (app) app.process().kill()
  }
}
main().then(() => process.exit(0), error => { console.error(error); process.exit(1) })
